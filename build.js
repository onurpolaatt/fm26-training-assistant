// node build.js  ->  dist/assistant.js (single file, wrapped so it never clashes with FMSuperScout globals)
const fs = require('fs'), path = require('path');
const pkg = require('./package.json');
const src = f => fs.readFileSync(path.join(__dirname, 'src', f), 'utf8');
const out = `// FM26 Training Assistant v${pkg.version} for FMSuperScout. Generated by build.js; do not edit.
// https://github.com/${pkg.repository || 'OWNER/fm26-training-assistant'}
(() => {
${src('i18n.js')}
${src('engine.js')}
${src('ui.js')}
})();
`;
fs.mkdirSync(path.join(__dirname, 'dist'), { recursive: true });
fs.writeFileSync(path.join(__dirname, 'dist', 'assistant.js'), out);
console.log(`dist/assistant.js  ${(out.length / 1024).toFixed(1)} KB`);
